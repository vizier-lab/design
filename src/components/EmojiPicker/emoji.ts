export function searchEmoji(query: string): EmojiEntry[] {
  const q = query.trim().toLowerCase();
  if (!q) return EMOJI;
  return EMOJI.filter((e) => e.name.includes(q) || (e.keywords ?? "").includes(q) || e.emoji === q);
}
