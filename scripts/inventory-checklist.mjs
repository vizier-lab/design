#!/usr/bin/env node
// Writes the README's "Inventory checklist" from the catalogue itself: one line
// per inventory id with its catalogue path and review status (SC-002).
//
//   node scripts/inventory-checklist.mjs            rewrite the README section
//   node scripts/inventory-checklist.mjs --check <inventory.md>
//                                                    also fail if an inventory id
//                                                    has no entry, or an entry has
//                                                    no inventory id
//
// Exits 1 with a one-line `error: …` on a mismatch.

import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const readme = path.join(root, "README.md");
const START = "<!-- inventory:start -->";
const END = "<!-- inventory:end -->";

function stories(dir, out = []) {
  for (const name of readdirSync(dir)) {
    const p = path.join(dir, name);
    if (statSync(p).isDirectory()) stories(p, out);
    else if (name.endsWith(".stories.tsx")) out.push(p);
  }
  return out;
}

const entries = [];
for (const file of stories(path.join(root, "src"))) {
  const text = readFileSync(file, "utf8");
  const id = /vizier:\s*\{\s*id:\s*"([A-Z]\d+)"/.exec(text)?.[1];
  const title = /title:\s*"([^"]+)"/.exec(text)?.[1];
  if (!id || !title) continue;
  const status = /tags:\s*\[[^\]]*"approved"/.test(text) ? "approved" : "needs-review";
  entries.push({ id, title, status, file: path.relative(root, file) });
}

const order = (id) => ({ B: 0, D: 1, X: 2 })[id[0]] * 1000 + Number(id.slice(1));
entries.sort((a, b) => order(a.id) - order(b.id));

const checkAt = process.argv.indexOf("--check");
if (checkAt > 0) {
  const inventory = readFileSync(process.argv[checkAt + 1], "utf8");
  const ids = new Set([...inventory.matchAll(/^\| ([BDX]\d+) \|/gm)].map((m) => m[1]));
  const have = new Set(entries.map((e) => e.id));
  const missing = [...ids].filter((i) => !have.has(i));
  const extra = [...have].filter((i) => !ids.has(i));
  if (missing.length || extra.length) {
    console.error(`error: missing from the catalogue: ${missing.join(", ") || "none"}; not in the inventory: ${extra.join(", ") || "none"}`);
    process.exit(1);
  }
}

const iconCount = Object.keys(
  Object.fromEntries([...readFileSync(path.join(root, "src/icons/map.ts"), "utf8").matchAll(/^ {2}"([a-z0-9-]+)": [A-Z]/gm)].map((m) => [m[1], 1])),
).length;
const approved = entries.filter((e) => e.status === "approved").length;

const lines = [
  START,
  "",
  `${entries.length} entries · ${approved} approved · ${entries.length - approved} need review. Generated by \`node scripts/inventory-checklist.mjs\`; don't edit by hand.`,
  "",
  "| | Id | Catalogue entry | Status |",
  "|---|----|-----------------|--------|",
  ...entries.map((e) => `| ${e.status === "approved" ? "✅" : "⬜"} | ${e.id} | \`${e.title}\` | ${e.status} |`),
  `| ✅ | I1, I2 | \`Icons/All\` (${iconCount} icons) | — |`,
  "",
  END,
];

const text = readFileSync(readme, "utf8");
const start = text.indexOf(START);
const end = text.indexOf(END);
if (start < 0 || end < 0) {
  console.error(`error: README.md has no ${START} … ${END} markers`);
  process.exit(1);
}
writeFileSync(readme, text.slice(0, start) + lines.join("\n") + text.slice(end + END.length));
console.log(`${entries.length} entries written to README.md`);
